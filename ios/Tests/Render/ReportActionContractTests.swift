import XCTest
@testable import Pervio

/// B2 — the rating buttons must land in the same places on both screens.
///
/// One publication spec (`actions`) drives two renderers: this app hangs a
/// `ReportActionMenuIcon` off every block whose text hits the regex, and
/// server/bin/pervio-view draws a `<span class="acts">` button group in the
/// same places for the Mac. If either side drifts — a block type stops
/// offering its text, a merge rule changes, a regex is recompiled differently —
/// a paper silently loses its 👍/👎 on one screen while keeping it on the
/// other, and the feedback loop that trains the digest quietly rots.
///
/// So both halves are pinned against the SAME real issues:
///   * this file recomputes the phone's hits from the shipping parser and
///     compares them to ios/Tests/Fixtures/reports/actions-contract.json;
///   * that json is not hand-written — it is generated by rendering those same
///     issues through the REAL pervio-view, and
///     `make_actions_contract.py --check` re-renders and fails on drift.
/// Phone drift turns this file red; server drift turns `--check` red — and
/// `--check` is run by `bash server/tests/run_all.sh` (its CHECKERS list). Until
/// it was wired in there, nothing in the repo ran it, so this comment described
/// a red that could not happen and the contract below could age unnoticed.
final class ReportActionContractTests: XCTestCase {

    /// The fold the 论文晨报 spec really ships (`display.collapseSections`).
    private let realCollapse = ["扫过"]

    // MARK: - the two sides read the same spec

    func testBothSidesCompileTheSameActionSpec() throws {
        let actions = try ReportFixture.actions()
        let contract = try ReportFixture.contract()
        // The server froze the spec it rendered with; it must be the spec the
        // phone is about to render with, or the comparison below is vacuous.
        XCTAssertEqual(actions, contract.actions,
                       "actions.json and the spec baked into actions-contract.json diverged — "
                       + "regenerate the contract")
        XCTAssertEqual(actions.count, 1)
        let a0 = try actions.at(0)
        XCTAssertEqual(a0.match, #"https://arxiv\.org/abs/(\d{4}\.\d{4,5})"#)
        XCTAssertEqual(a0.menu, ["👍", "👎", "少看", "多看"])
        // Both sides must have kept the action after compiling it: the phone
        // drops actions with a bad regex/empty menu, the server drops the same
        // shapes. A spec that survives on one side only is the worst case —
        // buttons on one screen, none on the other, and no error anywhere.
        XCTAssertEqual(CompiledAction.compile(actions).count, contract.compiledActionCount,
                       "one side dropped the action at compile time")
        XCTAssertEqual(contract.compiledActionCount, 1)
    }

    /// …and the sentence above is only true of the SHIPPED spec. Fed degenerate
    /// specs, the two compilers do not drop the same things — three shapes
    /// survive on the phone that pervio-view refuses outright, which is the
    /// worst failure mode there is: buttons on one screen, none on the other,
    /// no error anywhere. Both columns come from the machines (the server's from
    /// the real `_compile_actions`, frozen in actions-contract.json), so either
    /// side moving turns this red.
    func testKnownDivergence_theTwoCompilersDropDifferentBadSpecs() throws {
        let cases = try ReportFixture.contract().compileCases
        XCTAssertEqual(cases.map(\.label),
                       ["the shipped spec", "no match", "no menu", "no run",
                        "unparsable regex", "blank-only run", "empty label in menu",
                        "run with an unbalanced quote", "two good, one broken"],
                       "the frozen compile cases changed — regenerate and re-read them")

        let phone = cases.map { CompiledAction.compile($0.actions).count }
        let mac = cases.map(\.keptCount)
        XCTAssertEqual(mac, [1, 0, 0, 0, 0, 0, 0, 0, 2], "pervio-view's compile changed")
        XCTAssertEqual(phone, [1, 0, 0, 0, 0, 1, 1, 1, 2], "the phone's compile changed")

        let diverging = zip(cases, phone).filter { $0.0.keptCount != $0.1 }.map(\.0.label)
        XCTAssertEqual(diverging,
                       ["blank-only run", "empty label in menu",
                        "run with an unbalanced quote"],
                       "the set of specs the two screens disagree about moved — if a fix "
                       + "landed on the phone, shrink this list; if it grew, a new "
                       + "silent-divergence shape just shipped")

        // What each divergence would look like to a reader: a menu with a blank
        // button, or a button that builds a command nobody can parse.
        XCTAssertEqual(CompiledAction.compile([WorkflowAction(
            match: "x", menu: ["👍", ""], run: "cmd")]).first?.menu, ["👍", ""],
            "the phone would draw an unlabelled button")
        XCTAssertEqual(ActionCommand.build(run: "cmd 'oops", groups: [], choice: "👍"),
                       "cmd 'oops", "…and an unbalanced-quote template reaches the server verbatim")
    }

    // MARK: - hit-for-hit agreement on the real issues

    func testPhoneAndViewAgreeOnEveryButtonGroup() throws {
        let actions = try ReportFixture.actions()
        let contract = try ReportFixture.contract()
        XCTAssertEqual(Set(contract.reports.keys),
                       Set(ReportFixture.all.map { $0 + ".md" }),
                       "the contract and the fixture set disagree about which issues are frozen")

        for name in ReportFixture.all {
            let markdown = try ReportFixture.markdown(name)
            let server = try XCTUnwrap(contract.reports[name + ".md"],
                                       "no server contract for \(name)")
            let phone = ReportFixture.phoneHits(markdown, actions,
                                                collapseSections: realCollapse)

            // Count: how many papers can be scored on this issue.
            XCTAssertEqual(phone.count, server.buttonGroupCount,
                           "\(name): phone draws \(phone.count) rating menus, "
                           + "pervio-view draws \(server.buttonGroupCount) button groups")
            // The server's own two counts must agree (guards the HTML walk that
            // produced the contract from silently missing a group).
            XCTAssertEqual(server.buttonGroupCount, server.rawSpanCount,
                           "\(name): the contract's parsed groups and raw span count differ")

            // Position: same paper, in the same place, in the same order. This
            // is what makes a MOVED button red, not just a missing one.
            XCTAssertEqual(phone.map(\.groups), server.buttonGroups.map(\.groups),
                           "\(name): the papers offered for scoring, in document order, differ")
            XCTAssertEqual(phone.map(\.kind), server.buttonGroups.map(\.kind),
                           "\(name): a rating menu moved to a different kind of block")
            // Menu: the phone's items and the server's rendered <button> labels.
            // Indexed by the PHONE's count into the SERVER's array — the count
            // assertion above does not stop execution, so a regression that
            // makes the phone find more hits than the server would run off the
            // end. `at()` reports that as a failure instead of a SIGTRAP.
            for (i, hit) in phone.enumerated() {
                XCTAssertEqual(hit.menu, try server.buttonGroups.at(i).buttons,
                               "\(name): menu \(i) offers different choices on the two screens")
            }
        }
    }

    /// The counts are not trivially zero — a contract of "no buttons anywhere"
    /// would pass every assertion above while proving nothing.
    func testTheRealIssuesActuallyCarryButtons() throws {
        let contract = try ReportFixture.contract()
        let counts = ReportFixture.all.map { contract.reports[$0 + ".md"]?.buttonGroupCount ?? -1 }
        XCTAssertEqual(counts, [66, 1, 20, 0, 2, 5],
                       "the frozen issues changed shape — a digest with 66 scorable papers, "
                       + "one with a single 回看 link, one with 20, a GitHub issue with none "
                       + "(its links are github.com, not arxiv.org), the hostile report's 2, "
                       + "and the kinds sampler's 5 (one per block kind)")
        XCTAssertEqual(counts.reduce(0, +), 94)
    }

    /// Every block kind either renderer can hang a menu off is really exercised
    /// by the frozen set. Without the sampler only heading / listItem /
    /// paragraph appear, and the kind comparison above is inert for a quote —
    /// a mutation that reported a quote as a paragraph left the suite green.
    func testEveryBlockKindIsCoveredByTheFrozenSet() throws {
        let contract = try ReportFixture.contract()
        var kinds: Set<String> = []
        for name in ReportFixture.all {
            for g in try XCTUnwrap(contract.reports[name + ".md"]).buttonGroups {
                kinds.insert(g.kind)
            }
        }
        XCTAssertEqual(kinds, ["heading", "listItem", "quote", "paragraph"])
        let sampler = try XCTUnwrap(contract.reports[ReportFixture.sampler + ".md"])
        XCTAssertEqual(sampler.buttonGroups.map(\.kind),
                       ["paragraph", "heading", "quote", "listItem", "paragraph"],
                       "the sampler must keep one of each, in document order")
        XCTAssertEqual(sampler.buttonGroups.map(\.element),
                       ["p", "h3", "blockquote", "li", "div"],
                       "…and they must come from different HTML elements on the Mac, "
                       + "not from four paragraphs wearing different names")
    }

    /// Every group the server drew names a real paper id and the full menu —
    /// so "agreement" above cannot be agreement on empty values.
    func testEveryButtonGroupCarriesAPaperIdAndTheWholeMenu() throws {
        let contract = try ReportFixture.contract()
        var seen = 0
        for name in ReportFixture.all {
            for g in try XCTUnwrap(contract.reports[name + ".md"]).buttonGroups {
                XCTAssertEqual(g.buttons, ["👍", "👎", "少看", "多看"], "\(name): partial menu")
                XCTAssertEqual(g.groups.count, 1, "\(name): expected one capture group (the id)")
                let id = try g.groups.at(0)
                XCTAssertNotNil(id.range(of: #"^\d{4}\.\d{4,5}$"#, options: .regularExpression),
                                "\(name): \(id) is not an arxiv id")
                XCTAssertEqual(g.action, 0)
                seen += 1
            }
        }
        XCTAssertEqual(seen, 94)
    }

    /// A markdown table is the one construct only the phone has a block for:
    /// it renders a Grid, while pervio-view has no table branch at all and the
    /// pipe rows fall through as one paragraph. Both therefore offer exactly
    /// ONE rating menu, for the FIRST paper in the table — the same behaviour
    /// under two different internal names (`table` here, `paragraph` there),
    /// which is why `table` is a kind the contract can never contain. Pinned
    /// because that agreement is a coincidence of two parsers, and the day
    /// either learns real tables the counts move apart.
    func testATableOffersOneMenuForItsFirstPaperOnBothScreens() throws {
        let contract = try ReportFixture.contract()
        let table = contract.tableCase
        XCTAssertEqual(table.blockKinds, ["h", "p"],
                       "pervio-view grew a table block — the phone's Grid now has a peer")
        XCTAssertEqual(table.buttonGroupCount, 1)
        XCTAssertEqual(table.buttonGroupCount, table.rawSpanCount)
        XCTAssertEqual(table.buttonGroups.map(\.kind), ["paragraph"])
        XCTAssertEqual(table.buttonGroups.map(\.groups), [["2608.04788"]])

        let phone = ReportFixture.phoneHits(table.markdown, contract.actions)
        XCTAssertEqual(ReportFixture.blocks(table.markdown).map(\.testKind),
                       ["h2", "table(2)"], "the phone still parses a real table")
        XCTAssertEqual(phone.count, table.buttonGroupCount,
                       "one menu per screen, or the second paper is scoreable on one only")
        XCTAssertEqual(phone.map(\.groups), table.buttonGroups.map(\.groups))
        XCTAssertEqual(phone.map(\.kind), ["table"],
                       "…under the name only the phone uses")
        XCTAssertFalse(ReportFixture.all.contains { name in
            (try? ReportFixture.markdown(name)).map {
                ReportFixture.blocks($0).contains { $0.testKind.hasPrefix("table") }
            } ?? false
        }, "an issue grew a table — the kind comparison in the loop above will now "
         + "compare `table` to `paragraph` and go red; that is the bug, not this test")
    }

    // MARK: - the phone's fold must not eat a button

    /// The phone folds the 扫过 section behind a disclosure (the spec's
    /// `collapseSections`); the Mac has no such fold. Collapsing is a
    /// presentation choice and must be button-neutral — if it swallowed the
    /// folded papers' menus, 11 of the 20 papers in an issue would become
    /// unscoreable on the phone only.
    func testFoldingASectionChangesNoButton() throws {
        let actions = try ReportFixture.actions()

        // A section the hint really folds: `## 扫过` whose body is plain
        // bullets. Without this the neutrality check below would be vacuous —
        // see `testTheFoldHintIsInertOnEveryRealIssue` for why no archived
        // issue exercises it.
        let synthetic = """
        ## 扫过

        - [一](https://arxiv.org/abs/2608.04828) `★3.5`
        - [二](https://arxiv.org/abs/2608.04761) `★3.5`
        - [三](https://arxiv.org/abs/2608.04746) `★3.0`
        """
        let plain = ReportFixture.blocks(synthetic)
        let wrapped = MarkdownBlock.collapsed(plain, sections: realCollapse)
        XCTAssertFalse(plain.contains { $0.testDetailsBlocks != nil })
        XCTAssertTrue(wrapped.contains { $0.testDetailsBlocks != nil },
                      "collapseSections did not fold 扫过 — this check would be vacuous")
        XCTAssertEqual(ReportFixture.phoneHits(synthetic, actions),
                       ReportFixture.phoneHits(synthetic, actions, collapseSections: realCollapse),
                       "folding 扫过 changed the rating menus — folded papers became unscoreable")
        XCTAssertEqual(
            ReportFixture.phoneHits(synthetic, actions, collapseSections: realCollapse).count, 3)

        // And on the real issues, folding is likewise button-neutral.
        for name in ReportFixture.all {
            let markdown = try ReportFixture.markdown(name)
            XCTAssertEqual(ReportFixture.phoneHits(markdown, actions),
                           ReportFixture.phoneHits(markdown, actions,
                                                   collapseSections: realCollapse),
                           "\(name): folding 扫过 changed the rating menus")
        }
    }

    /// Why the loop above cannot be the whole story: on every archived issue the
    /// legacy `collapseSections` hint is INERT, for two different reasons —
    /// 2026-08-06 and the hostile report already fold themselves with a literal
    /// `<details>` (the guard rail against fold-inside-fold), and 2026-07-18
    /// names its section `一句话扫过`, which the hint matches exactly and so
    /// does not match at all. Pinned because it is easy to believe the hint is
    /// doing work it is not.
    func testTheFoldHintIsInertOnEveryRealIssue() throws {
        for name in ReportFixture.realArchives {
            let blocks = ReportFixture.blocks(try ReportFixture.markdown(name))
            XCTAssertEqual(MarkdownBlock.collapsed(blocks, sections: realCollapse).map(\.testKind),
                           blocks.map(\.testKind),
                           "\(name): the fold hint changed the block shape")
        }
        let old = ReportFixture.blocks(try ReportFixture.markdown("papers-2026-07-18"))
        XCTAssertTrue(old.contains { $0.testKind == "h2" && $0.testText == "一句话扫过" },
                      "2026-07-18's section is named 一句话扫过, not 扫过")
        XCTAssertFalse(old.contains { $0.testDetailsBlocks != nil },
                       "…and it has no literal <details>, so it simply never folds")
    }

    // MARK: - the capture group is what gets scored

    /// The id in the button group is the id the server command will carry, and
    /// every substituted value is shell-quoted. A drift here scores the WRONG
    /// paper — silent, and it teaches the digest the opposite of what the user
    /// meant.
    func testTheCommandBuiltForARealPaperNamesThatPaper() throws {
        let actions = try ReportFixture.actions()
        let compiled = CompiledAction.compile(actions)
        let markdown = try ReportFixture.markdown("papers-2026-08-06")
        let blocks = ReportFixture.blocks(markdown)
        let hits = MarkdownBlock.actionHits(blocks, compiled)
        let first = try XCTUnwrap(hits.first)
        XCTAssertEqual(first.hit.groups, ["2608.04788"])
        XCTAssertEqual(
            ActionCommand.build(run: first.hit.action.run, groups: first.hit.groups, choice: "👍"),
            "~/.pervio/bin/pervio-feedback --id '2608.04788' --verdict '👍'")
        // …and the ids run in document order, matching the issue's own order.
        XCTAssertEqual(hits.prefix(4).map(\.hit.groups),
                       [["2608.04788"], ["2608.04962"], ["2608.05080"], ["2608.04405"]])
    }

    // MARK: - KNOWN DIVERGENCE (reported, not yet fixed)

    /// The two renderers cut paragraphs differently, and it is load-bearing.
    ///
    /// pervio-view lifts a whole-line bare URL into its own `chip` block and a
    /// `A · B · C` metadata line into its own `data` block, so each gets its own
    /// button group. The phone keeps the run as ONE `.paragraph` and matches the
    /// merged text, so `firstHit` fires once — the first URL wins and every
    /// later match in the same run is unreachable.
    ///
    /// No published issue triggers this yet: the arxiv action only matches
    /// arxiv.org links, and no archived digest puts two of those on adjacent
    /// lines. The day a generator does, the Mac will show two 👍 rows and the
    /// phone one, and `testPhoneAndViewAgreeOnEveryButtonGroup` above goes red
    /// on the real issue. This test pins the mechanism now, so the report says
    /// what will break rather than merely that something did.
    /// Both halves are machine-produced: the Mac's numbers come from
    /// actions-contract.json (the real pervio-view rendering the very markdown
    /// stored beside them), the phone's from the shipping parser. So the gap is
    /// pinned from BOTH ends — the phone closing it turns this red, and the Mac
    /// closing it (or widening it) turns `make_actions_contract.py --check` red
    /// under `bash server/tests/run_all.sh`, which is what actually runs it.
    func testKnownDivergence_adjacentBareURLsCollapseToOneMenuOnThePhone() throws {
        let actions = try ReportFixture.actions()
        let mac = try ReportFixture.contract().bareURLRunCase
        let markdown = mac.markdown

        // The Mac: each whole-line URL is its own chip block with its own group.
        XCTAssertEqual(mac.blockKinds, ["h", "chip", "chip"],
                       "pervio-view stopped lifting whole-line URLs into chips")
        XCTAssertEqual(mac.buttonGroupCount, 2)
        XCTAssertEqual(mac.buttonGroupCount, mac.rawSpanCount)
        XCTAssertEqual(mac.buttonGroups.map(\.groups), [["2608.04788"], ["2608.04962"]],
                       "both papers are scorable on the Mac")

        // The phone: one paragraph, so `firstHit` fires once and the second
        // paper cannot be rated at all.
        let blocks = ReportFixture.blocks(markdown)
        XCTAssertEqual(blocks.map(\.testKind), ["h2", "p"],
                       "the phone merges both URL lines into one paragraph")
        let hits = ReportFixture.phoneHits(markdown, actions)
        XCTAssertEqual(hits.map(\.groups), [["2608.04788"]],
                       "phone: only the FIRST paper of the run is scorable")

        // The gap itself, as a number: one paper the Mac can rate and the phone
        // cannot. No published issue puts two arxiv links on adjacent lines yet
        // — the day a generator does, this is what the reader loses.
        XCTAssertEqual(mac.buttonGroupCount - hits.count, 1,
                       "the adjacent-bare-URL divergence changed size")
    }
}
